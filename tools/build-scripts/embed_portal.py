#!/usr/bin/env python3
"""
Pre-build script for PlatformIO: embeds the web panel page in the firmware.

Gzips web/portal/index.html (PORTAL_PAGE_SOURCE in src/config/portal.h) into a C array header under the
build directory (never committed) and adds that directory to the include path. The build fails with a clear
message when the source is missing or the gzip page is larger than PORTAL_PAGE_BUDGET_BYTES (same header).
The generated header defines PORTAL_PAGE_GZ_SIZE, PORTAL_PAGE_GZ_CRC32 and the array portal_page_gz; the
firmware builds its ETag from the build number and the CRC (network/portal_page_logic.*).
"""

try:
    Import("env")
    platformio_mode = True
except Exception:
    platformio_mode = False

import gzip
import os
import re
import sys
import zlib

CONFIG_HEADER = os.path.join("src", "config", "portal.h")
GENERATED_DIR_NAME = "portal_generated"
GENERATED_HEADER_NAME = "portal_page_data.h"


class PortalEmbedError(Exception):
    """The page cannot be embedded; the message says why and what to do."""


def read_define(project_dir, name, numeric=False):
    """Value of '#define NAME value' in src/config/portal.h (single source of truth for C++ and this script)."""
    path = os.path.join(project_dir, CONFIG_HEADER)
    try:
        with open(path, "r", encoding="utf-8") as f:
            text = f.read()
    except OSError as e:
        raise PortalEmbedError(f"Cannot read {CONFIG_HEADER}: {e}")
    pattern = r"^#define\s+" + re.escape(name) + r"\s+" + (r"(\d+)" if numeric else r'"([^"]*)"')
    match = re.search(pattern, text, re.MULTILINE)
    if not match:
        raise PortalEmbedError(f"{name} is not defined in {CONFIG_HEADER}")
    return int(match.group(1)) if numeric else match.group(1)


def gzip_page(data):
    """Deterministic gzip (no timestamp), so an unchanged page gives an identical header."""
    return gzip.compress(data, compresslevel=9, mtime=0)


def render_header(gz, source_rel):
    """C header text for a gzip page."""
    rows = []
    for i in range(0, len(gz), 16):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in gz[i:i + 16]) + ",")
    body = "\n".join(rows)
    return (
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        "// Generated by tools/build-scripts/embed_portal.py from " + source_rel + " - DO NOT EDIT, never committed\n"
        f"#define PORTAL_PAGE_GZ_SIZE {len(gz)}u\n"
        f"#define PORTAL_PAGE_GZ_CRC32 0x{zlib.crc32(gz) & 0xFFFFFFFF:08x}u\n\n"
        "static const uint8_t portal_page_gz[PORTAL_PAGE_GZ_SIZE] = {\n" + body + "\n};\n"
    )


def embed_page(project_dir, out_dir):
    """Builds the header in out_dir. Returns (header_path, gzip_size, raw_size). Raises PortalEmbedError."""
    source_rel = read_define(project_dir, "PORTAL_PAGE_SOURCE")
    budget = read_define(project_dir, "PORTAL_PAGE_BUDGET_BYTES", numeric=True)
    source = os.path.join(project_dir, *source_rel.split("/"))
    if not os.path.isfile(source):
        raise PortalEmbedError(f"Web panel page missing: {source_rel} (expected at {source}). "
                               "The firmware embeds it; restore the file or fix PORTAL_PAGE_SOURCE in src/config/portal.h.")
    with open(source, "rb") as f:
        raw = f.read()
    if not raw.strip():
        raise PortalEmbedError(f"Web panel page is empty: {source_rel}")
    gz = gzip_page(raw)
    if len(gz) > budget:
        raise PortalEmbedError(f"Web panel page is too large: {len(gz)} bytes gzipped ({len(raw)} raw), budget is "
                               f"{budget} bytes (PORTAL_PAGE_BUDGET_BYTES in src/config/portal.h). Shrink {source_rel}.")
    os.makedirs(out_dir, exist_ok=True)
    header_path = os.path.join(out_dir, GENERATED_HEADER_NAME)
    text = render_header(gz, source_rel)
    try:
        with open(header_path, "r", encoding="utf-8") as f:
            unchanged = f.read() == text
    except OSError:
        unchanged = False
    if not unchanged:  # keep the timestamp when nothing changed, so the compiler does not rebuild for nothing
        with open(header_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    return header_path, len(gz), len(raw)


def run_platformio():
    project_dir = env.get("PROJECT_DIR", os.getcwd())
    out_dir = os.path.join(env.subst("$BUILD_DIR"), GENERATED_DIR_NAME)
    try:
        header_path, gz_size, raw_size = embed_page(project_dir, out_dir)
    except PortalEmbedError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        env.Exit(1)
        return
    env.Append(CPPPATH=[out_dir])
    print(f"Embedded web panel page: {raw_size} bytes -> {gz_size} bytes gzip ({header_path})")


if platformio_mode:
    run_platformio()
